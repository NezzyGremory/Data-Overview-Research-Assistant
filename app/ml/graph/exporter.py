def export_model_pkl(model_obj: Any, output_path: Union[str, Path]) -> str:
    """Save trained model estimator to .pkl using joblib."""
    out_p = Path(output_path)
    out_p.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(model_obj, out_p)
    return str(out_p.resolve())


def export_runs_csv(runs: List[Dict[str, Any]], output_path: Optional[Union[str, Path]] = None) -> pd.DataFrame:
    """Flatten run history entries into a summary pandas DataFrame and optional CSV."""
    rows = []
    for r in runs:
        metrics = r.get("metrics", {})
        row = {
            "run_id": r.get("id"),
            "graph_version_id": r.get("graph_version_id"),
            "status": r.get("status"),
            "dataset_hash": r.get("dataset_hash"),
            "duration_ms": r.get("duration_ms"),
            "random_state": r.get("random_state"),
            "created_at": r.get("created_at"),
            "notes": r.get("notes", ""),
        }
        for k, v in metrics.items():
            if isinstance(v, (int, float, str, bool)):
                row[f"metric_{k}"] = v
        rows.append(row)

    df = pd.DataFrame(rows)
    if output_path:
        out_p = Path(output_path)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(out_p, index=False)
    return df


def export_project_zip(
    project_dict: Dict[str, Any],
    graph_dict: Dict[str, Any],
    runs: List[Dict[str, Any]],
    output_zip_path: Union[str, Path],
    dataset_df: Optional[pd.DataFrame] = None,
    target_column: str = "target",
    task: str = "classification",
) -> Path:
    """Package complete experiment artifacts into a single portable ZIP file."""
    zip_p = Path(output_zip_path)
    zip_p.parent.mkdir(parents=True, exist_ok=True)

    script_py = export_python_script(graph_dict, target_column, task)
    notebook = export_jupyter_notebook(graph_dict, target_column, task, dataset_name="dataset.csv")
    runs_df = export_runs_csv(runs)

    with zipfile.ZipFile(zip_p, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("project.json", json.dumps(project_dict, indent=2, ensure_ascii=False))
        zf.writestr("graph.json", json.dumps(graph_dict, indent=2, ensure_ascii=False))
        zf.writestr("pipeline.py", script_py)
        zf.writestr("notebook.ipynb", json.dumps(notebook, indent=2))
        zf.writestr("runs_summary.csv", runs_df.to_csv(index=False))

        if dataset_df is not None:
            zf.writestr("dataset.csv", dataset_df.to_csv(index=False))

    return zip_p

