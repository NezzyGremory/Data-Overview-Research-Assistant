def export_python_script(
    graph_dict: Dict[str, Any],
    target_column: str = "target",
    task: str = "classification",
) -> str:
    """
    Generate clean, standalone Python script replicating the graph using native scikit-learn Pipeline.
    Includes argparse CLI `--data <path>` so it can run independently on any machine.
    """
    nodes = graph_dict.get("nodes", [])
    model_node = next((n for n in nodes if str(n.get("spec_id", "")).startswith("model:") or "classifier" in str(n.get("spec_id", "")).lower() or "regressor" in str(n.get("spec_id", "")).lower()), None)
    prep_node = next((n for n in nodes if n.get("spec_id") in ("preprocess", "scale")), None)
    split_node = next((n for n in nodes if n.get("spec_id") == "split"), None)

    test_size = 0.25
    random_state = 42
    if split_node and "parameters" in split_node:
        test_size = float(split_node["parameters"].get("test_size", 0.25))
        random_state = int(split_node["parameters"].get("random_state", 42))

    # Determine estimator class and params
    est_cls = "RandomForestClassifier"
    est_module = "sklearn.ensemble"
    est_params = {"random_state": random_state}

    if model_node:
        spec_id = model_node.get("spec_id", "")
        params = model_node.get("parameters", {})
        est_params.update(params)

        if "decision_tree" in spec_id:
            est_cls = "DecisionTreeClassifier" if "class" in spec_id or task == "classification" else "DecisionTreeRegressor"
            est_module = "sklearn.tree"
        elif "random_forest" in spec_id:
            est_cls = "RandomForestClassifier" if "class" in spec_id or task == "classification" else "RandomForestRegressor"
            est_module = "sklearn.ensemble"
        elif "gradient_boosting" in spec_id or "hist_gradient_boosting" in spec_id:
            est_cls = "HistGradientBoostingClassifier" if "class" in spec_id or task == "classification" else "HistGradientBoostingRegressor"
            est_module = "sklearn.ensemble"
        elif "logistic_regression" in spec_id or "logistic" in spec_id:
            est_cls = "LogisticRegression"
            est_module = "sklearn.linear_model"
        elif "ridge" in spec_id:
            est_cls = "Ridge"
            est_module = "sklearn.linear_model"
        elif "linear_regression" in spec_id:
            est_cls = "LinearRegression"
            est_module = "sklearn.linear_model"
        elif "kmeans" in spec_id:
            est_cls = "KMeans"
            est_module = "sklearn.cluster"
            task = "clustering"

    scaler_cls = "StandardScaler"
    if prep_node:
        scaler_type = prep_node.get("parameters", {}).get("scaler", "standard")
        if scaler_type == "robust":
            scaler_cls = "RobustScaler"
        elif scaler_type == "minmax":
            scaler_cls = "MinMaxScaler"

    param_str = ", ".join(f"{k}={repr(v)}" for k, v in est_params.items())

    script = f'''"""Standalone ML pipeline generated by DORA Dataset Research."""

import argparse
import json
import sys
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import {scaler_cls}, OneHotEncoder
from sklearn.impute import SimpleImputer
from {est_module} import {est_cls}
from sklearn.metrics import accuracy_score, f1_score, precision_score, recall_score, mean_squared_error, r2_score, mean_absolute_error


def build_pipeline():
    numeric_transformer = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", {scaler_cls}()),
    ])
    categorical_transformer = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
    ])

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", numeric_transformer, lambda X: X.select_dtypes(include="number").columns.tolist()),
            ("cat", categorical_transformer, lambda X: X.select_dtypes(exclude="number").columns.tolist()),
        ],
        remainder="passthrough",
    )

    model = {est_cls}({param_str})

    return Pipeline([
        ("preprocessor", preprocessor),
        ("model", model),
    ])


def main():
    parser = argparse.ArgumentParser(description="Run standalone exported ML pipeline.")
    parser.add_argument("--data", type=str, required=True, help="Path to CSV dataset")
    parser.add_argument("--target", type=str, default="{target_column}", help="Target column name")
    parser.add_argument("--test-size", type=float, default={test_size}, help="Test split ratio")
    parser.add_argument("--seed", type=int, default={random_state}, help="Random seed")
    args = parser.parse_args()

    df = pd.read_csv(args.data)
    if args.target not in df.columns:
        print(f"Error: Target column '{{args.target}}' not found in dataset.", file=sys.stderr)
        sys.exit(1)

    X = df.drop(columns=[args.target])
    y = df[args.target]

    is_classification = "{task}" == "classification"
    stratify = y if (is_classification and y.nunique() < 20 and len(y) > 20) else None

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=args.test_size, random_state=args.seed, stratify=stratify
    )

    pipeline = build_pipeline()
    pipeline.fit(X_train, y_train)
    y_pred = pipeline.predict(X_test)

    if is_classification:
        metrics = {{
            "accuracy": float(accuracy_score(y_test, y_pred)),
            "f1_macro": float(f1_score(y_test, y_pred, average="macro", zero_division=0)),
            "precision": float(precision_score(y_test, y_pred, average="macro", zero_division=0)),
            "recall": float(recall_score(y_test, y_pred, average="macro", zero_division=0)),
        }}
    else:
        metrics = {{
            "r2": float(r2_score(y_test, y_pred)),
            "rmse": float(np.sqrt(mean_squared_error(y_test, y_pred))),
            "mae": float(mean_absolute_error(y_test, y_pred)),
        }}

    print(json.dumps(metrics, indent=2))
    return metrics


if __name__ == "__main__":
    main()
'''
    return script


